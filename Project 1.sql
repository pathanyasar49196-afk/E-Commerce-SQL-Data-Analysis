-- Q13. Rank customers based on their total spending on delivered orders.
with customer_sales as
(select c.customer_id, c.customer_name, sum(oi.quantity * oi.unit_price *
(1 - oi.discount_pct / 100.0)) as total_spending
from customers c
inner join orders o 
on c.customer_id = o.customer_id
inner join order_items oi
on o.order_id = oi.order_id
where o.order_status = 'Delivered'
group by c.customer_id, c.customer_name
),
customer_ranking as
(select customer_name, total_spending,
dense_rank() over (order by total_spending desc) as customer_rank
from customer_sales
)
select *
from customer_ranking
order by customer_rank;

-- Q14. Find customers who have placed more than 5 successfully delivered orders
-- and rank them based on their total number of delivered orders.
with customer_orders as
(select c.customer_id, c.customer_name, count(o.order_id) as total_orders
from customers c
inner join orders o
on c.customer_id = o.customer_id
where o.order_status = 'Delivered'
group by c.customer_id, c.customer_name
having count(o.order_id) > 5
),
customer_ranking as
(select customer_name, total_orders,
dense_rank() over (order by total_orders desc) as customer_rank
from customer_orders
)
select *
from customer_ranking
order by customer_rank;

-- Q15. Calculate each customer's percentage contribution to total delivered sales revenue.
with customer_sales as
(select c.customer_id, c.customer_name, sum(oi.quantity * oi.unit_price *
(1 - oi.discount_pct / 100.0)) as total_spending
from customers c
inner join orders o
on c.customer_id = o.customer_id
inner join order_items oi
on o.order_id = oi.order_id
where o.order_status = 'Delivered'
group by c.customer_id,c.customer_name
)
select customer_name, total_spending,
ROUND((total_spending / sum(total_spending) over()) * 100,2) as revenue_contribution_pct
from customer_sales
order by total_spending desc;