-- Q6. How much sales revenue was generated each month from successfully delivered 
-- orders after applying discounts?
select date_trunc('Month', o.order_date):: date as sales_month,
sum(oi.quantity*oi.unit_price*(1-oi.discount_pct/100.0)) as total_revenue
from orders as o
inner join order_items as oi
on o.order_id = oi.order_id
where o.order_status = 'Delivered'
group by date_trunc('Month', o.order_date)
order by sales_month asc;

