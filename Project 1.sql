-- Q1. What is the total sales revenue generated from delivered orders?
with sales_data as (
select oi.quantity, oi.unit_price, oi.discount_pct
from order_items as oi
inner join orders as o
on oi.order_id = o.order_id
where o.order_status = 'Delivered'
)
select sum(quantity * unit_price *(1 - discount_pct / 100)
) as total_revenue
from sales_data;

-- Q2. How many orders were successfully delivered?
select count(order_id) as Deli_count
from orders
where order_status = 'Delivered'

-- Q3. What is the average order value of successfully delivered orders 
-- after applying discounts?
select Avg(order_total) as avg_order_value
from ( select o.order_id, Sum(oi.quantity * oi.unit_price *
(1 - coalesce(oi.discount_pct, 0) / 100.0)
) as order_total
from orders as o
inner join order_items as oi
on o.order_id = oi.order_id
where o.order_status = 'Delivered'
group by o.order_id
) as sales;

-- Q4. Which 5 products generated the highest total sales revenue 
-- from successfully delivered orders after applying discounts?
select p.product_id, p.product_name, ROUND(sum(oi.quantity * oi.unit_price *
(1 - coalesce(oi.discount_pct, 0) / 100.0)), 2) as total_revenue
from orders o
inner join order_items as oi 
on o.order_id = oi.order_id
inner join products as p     
on oi.product_id = p.product_id
where o.order_status = 'Delivered'
group by p.product_id, p.product_name
order by total_revenue desc
limit 5;

-- Q5. What is the total sales revenue generated by each product category 
-- from successfully delivered orders after applying discounts?
