-- Q11. Find the top 3 highest revenue-generating products within each category
-- using a window function.
with product_revenue as
(select p.category, p.product_name, sum(oi.quantity * oi.unit_price *
(1 - oi.discount_pct / 100.0)) as total_revenue
from products p
inner join order_items oi
on p.product_id = oi.product_id
inner join orders o
on oi.order_id = o.order_id
where o.order_status = 'Delivered'
group by p.product_id, p.category, p.product_name
),
ranked_products as
(select category, product_name, total_revenue,dense_rank() over (
partition by category order by total_revenue DESC
) as product_rank
from product_revenue
)
select *
from ranked_products
where product_rank <= 3
order by category, product_rank;

-- Q12. Calculate the monthly sales revenue and percentage growth compared to the
-- previous month for successfully delivered orders.
with monthly_sales as
(select date_trunc('month', o.order_date):: date AS sales_month,
SUM(oi.quantity * oi.unit_price *(1 - oi.discount_pct / 100.0)) AS total_revenue
FROM orders as o
INNER JOIN order_items as oi
ON o.order_id = oi.order_id
WHERE o.order_status = 'Delivered'
GROUP BY DATE_TRUNC('month', o.order_date)
),
previous_sales as
(select sales_month, total_revenue,
lag(total_revenue) over (order by sales_month) as previous_month_revenue
from monthly_sales
)
select to_char(sales_month, 'Mon YYYY') as sales_month,total_revenue,
previous_month_revenue,
ROUND(((total_revenue - previous_month_revenue)/ nullif(previous_month_revenue, 0))*
100,2) as growth_pct
from previous_sales
order by previous_sales.sales_month;

